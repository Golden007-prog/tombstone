"""Generate the teleprompter cut of the demo script: the spoken words, and nothing else.

`docs/DEMO-SCRIPT.md` is written to be *planned* from — stage directions, on-screen notes, word
budgets, and the reasoning for what was cut. None of that is readable while you are also driving
a UI and watching a clock, and the recording checklist already says to record the voiceover
separately from the capture. So this writes the narration on its own, with its cue times.

It imports the beat regex and the narration extractor from `scripts_check_demo_timing.py` rather
than writing its own. A second parser for one format is exactly the duplication that put a stale
count in the blog post and a stale figure in three documents this week.

    python3 scripts_build_narration.py            # write docs/DEMO-NARRATION.md
    python3 scripts_build_narration.py --check     # fail if it is out of date

The --check form runs in the push gate: it needs no database and no browser, so there is no
reason for the generated file to be allowed to drift from its source.
"""
from __future__ import annotations

import re
import sys

from scripts_check_demo_timing import PATH, narration, split_beats

OUT = "docs/DEMO-NARRATION.md"


def build() -> tuple[str, int]:
    text = open(PATH, encoding="utf-8").read()
    beats = split_beats(text)
    rows, total = [], 0
    for i in range(1, len(beats), 5):
        start, end, title, budget, body = beats[i:i + 5]
        spoken = narration(body)
        words = len(spoken.split())
        total += words
        # Sentence per line, because a wall of prose is the thing that makes a reader lose their
        # place on take four. The split keeps the terminator with the sentence it ends.
        lines = [t.strip() for t in re.split(r"(?<=[.?!])\s+", spoken) if t.strip()]
        rows.append((start, end, title.strip(), int(budget), words, lines))

    out = [
        "# Narration only — read this while recording",
        "",
        f"Generated from [`{PATH.split('/')[-1]}`]({PATH.split('/')[-1]}) by "
        f"`scripts_build_narration.py`. **Do not edit this file**; edit the script and "
        f"regenerate, or the push gate will stop you.",
        "",
        "Every stage direction, screen note and word budget lives in the script. What is left "
        "here is what you say.",
        "",
        f"**{total} words across 180 seconds.** Record the voiceover separately from the screen "
        f"capture — the checklist in the script explains why, and it is the single biggest cause "
        f"of a bad night.",
        "",
        "---",
        "",
    ]
    for start, end, title, budget, words, lines in rows:
        out.append(f"### {start} → {end} · {title}")
        out.append("")
        out.append(f"*{words} words, {int(end.split(':')[0]) * 60 + int(end.split(':')[1]) - (int(start.split(':')[0]) * 60 + int(start.split(':')[1]))} seconds.*")
        out.append("")
        for ln in lines:
            out.append(f"{ln}")
            out.append("")
        out.append("---")
        out.append("")
    return "\n".join(out).rstrip() + "\n", total


def main() -> int:
    fresh, spoken_total = build()
    if "--check" in sys.argv:
        try:
            have = open(OUT, encoding="utf-8").read()
        except OSError:
            print(f"  FAIL  {OUT} does not exist; run python3 scripts_build_narration.py")
            return 1
        if have != fresh:
            print(f"  FAIL  {OUT} is out of date with {PATH}; regenerate it")
            return 1
        # The total comes from the beats, not from re-counting the rendered file. Counting the
        # output included this file's own header prose and reported 531 against the 489 printed
        # two lines above it in the same output -- a second number for one quantity, which is the
        # defect this repository has spent two days removing from its documents.
        print(f"  the narration cut matches the script it is generated from "
              f"({spoken_total} spoken words)")
        return 0
    open(OUT, "w", encoding="utf-8").write(fresh)
    print(f"  wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
